# Set up the local RTSP relay (mediamtx) so the analysis and the recording share one camera connection per
# stream. The Tapo cameras accept about 3 RTSP sessions each; analysis (2) + recording (2) per device is 4.
#
#   1. unzip mediamtx_vX_windows_amd64.zip into C:\Users\<user>\mediamtx (https://github.com/bluenviron/mediamtx)
#   2. put the direct camera URLs in cameras.direct.txt (same format as cameras.txt; never committed)
#   3. run as administrator:  powershell -ExecutionPolicy Bypass -File setup_relay.ps1
#
# Writes mediamtx.yml (one on-demand path per camera, named after its URL: 101/stream2 ...), registers the
# PoseMakerRelay task (SYSTEM, at startup, restarts on failure), starts it, and points cameras.txt at the relay.
param([string]$MediaMtxDir = "$env:USERPROFILE\mediamtx")

$ErrorActionPreference = 'Stop'
$repo = $PSScriptRoot
$direct = Join-Path $repo 'cameras.direct.txt'
if (-not (Test-Path $direct)) {
    if (-not (Test-Path (Join-Path $repo 'cameras.txt'))) { throw 'cameras.direct.txt / cameras.txt missing' }
    Copy-Item (Join-Path $repo 'cameras.txt') $direct                # first run: cameras.txt still holds the camera URLs
}
$urls = @(Get-Content $direct | ForEach-Object { $_.Trim() } | Where-Object { $_ -and -not $_.StartsWith('#') })
if ($urls[0] -like 'rtsp://127.0.0.1:*') { throw 'cameras.direct.txt holds relay URLs; put the camera URLs there' }

$yml = @(
    '# Generated by pose-maker\setup_relay.ps1 from cameras.direct.txt.',
    'logLevel: info', 'logDestinations: [file]', "logFile: $($MediaMtxDir -replace '\\', '/')/mediamtx.log",
    'rtspAddress: 127.0.0.1:8554', 'rtspTransports: [tcp]',
    'rtmp: false', 'hls: false', 'webrtc: false', 'srt: false', 'moq: false',
    'paths:')
$names = @()
foreach ($u in $urls) {
    $m = [regex]::Match($u, '^rtsp://[^/]*?(\d+)(:\d+)?/(.+)$')        # .../192.168.50.101/stream2 -> 101/stream2
    $name = '{0}/{1}' -f $m.Groups[1].Value, $m.Groups[3].Value
    $names += $name
    $yml += "  ${name}:", "    source: $u", '    rtspTransport: tcp', '    sourceOnDemand: true', '    sourceOnDemandCloseAfter: 30s'
}
[IO.File]::WriteAllLines((Join-Path $MediaMtxDir 'mediamtx.yml'), $yml)

$exe = Join-Path $MediaMtxDir 'mediamtx.exe'
$act = New-ScheduledTaskAction -Execute $exe -Argument (Join-Path $MediaMtxDir 'mediamtx.yml') -WorkingDirectory $MediaMtxDir
$trg = New-ScheduledTaskTrigger -AtStartup
$pri = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
$set = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -ExecutionTimeLimit ([TimeSpan]::Zero) `
    -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1)
Register-ScheduledTask -TaskName PoseMakerRelay -Action $act -Trigger $trg -Principal $pri -Settings $set -Force `
    -Description 'RTSP relay for the cameras (mediamtx): analysis and recording share one camera connection per stream' | Out-Null
Stop-ScheduledTask PoseMakerRelay -ErrorAction SilentlyContinue
Start-ScheduledTask PoseMakerRelay

$relay = @('# Cameras through the local RTSP relay (mediamtx, task PoseMakerRelay). Direct camera URLs: cameras.direct.txt') +
         ($names | ForEach-Object { "rtsp://127.0.0.1:8554/$_" })
[IO.File]::WriteAllLines((Join-Path $repo 'cameras.txt'), $relay)
"relay paths: $($names -join ', ')"
'cameras.txt now points at rtsp://127.0.0.1:8554/...'
